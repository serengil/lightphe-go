// Domains separating the proofs of ElGamal from proofs of other statements.
const (
	DecryptionDomain        = "lightphe/elgamal/decryption"
	PartialDecryptionDomain = "lightphe/elgamal/partial-decryption"
	MembershipDomain        = "lightphe/exponential-elgamal/membership"
)

// ErrPrimeOrderRequired reports threshold decryption or a zero-knowledge
// proof requested with keys whose generator has no known prime order.
var ErrPrimeOrderRequired = errors.New("lightphe: public key does not have the order q of the generator, which " +
	"threshold decryption and zero-knowledge proofs require, generate new keys with a prime order to use them")

var (
	_ phe.ThresholdDecrypter = (*Cryptosystem)(nil)
	_ phe.DecryptionProver   = (*Cryptosystem)(nil)
	_ phe.MembershipProver   = (*Cryptosystem)(nil)
	_ phe.KnowledgeProver    = (*Cryptosystem)(nil)
)

// GeneratePrimeOrder creates a fresh key pair where p = k q + 1 for a large
// prime q, and g has order q. Threshold decryption and zero-knowledge proofs
// require the order of g to be known and prime.
func GeneratePrimeOrder(keySize int, exponential bool) (*Cryptosystem, error) {
	if keySize <= 0 {
		keySize = DefaultKeySize
	}
	bits := keySize / 2
	if bits < 8 {
		bits = 8
	}
	kBits := bits / 4
	if kBits > 16 {
		kBits = 16
	}
	if kBits < 1 {
		kBits = 1
	}
	qBits := bits - kBits

	// picking a prime modulus p = k q + 1 for a prime q
	var p, q, k *big.Int
	lo := new(big.Int).Lsh(big.NewInt(1), uint(kBits-1))
	hi := new(big.Int).Lsh(big.NewInt(1), uint(kBits))
	for tries := 0; p == nil; tries++ {
		if tries == 10000 {
			return nil, fmt.Errorf("elgamal: no prime modulus of a prime order subgroup found: %w", phe.ErrKeyGeneration)
		}
		candidate, err := mathutil.RandPrime(qBits)
		if err != nil {
			return nil, fmt.Errorf("elgamal: %w", err)
		}
		for i := 0; i < 1000; i++ {
			half, err := mathutil.RandRange(lo, hi)
			if err != nil {
				return nil, fmt.Errorf("elgamal: %w", err)
			}
			kc := new(big.Int).Lsh(half, 1)
			pc := new(big.Int).Mul(kc, candidate)
			pc.Add(pc, big.NewInt(1))
			if pc.BitLen() <= bits && mathutil.IsPrime(pc) {
				p, q, k = pc, candidate, kc
				break
			}
		}
	}

	// picking a generator g of the subgroup of prime order q
	var g *big.Int
	for {
		h, err := mathutil.RandRange(big.NewInt(2), new(big.Int).Sub(p, big.NewInt(2)))
		if err != nil {
			return nil, fmt.Errorf("elgamal: %w", err)
		}
		if g = new(big.Int).Exp(h, k, p); g.Cmp(big.NewInt(1)) != 0 {
			break
		}
	}

	// picking a private key x
	x, err := mathutil.RandRange(big.NewInt(1), new(big.Int).Sub(q, big.NewInt(1)))
	if err != nil {
		return nil, fmt.Errorf("elgamal: %w", err)
	}

	return New(Keys{
		PublicKey:  &PublicKey{P: p, G: g, Y: new(big.Int).Exp(g, x, p), Q: q},
		PrivateKey: &PrivateKey{X: x},
	}, exponential)
}

// group returns the subgroup of prime order q generated by g.
func (c *Cryptosystem) group() (zkp.ModularGroup, error) {
	q := c.keys.PublicKey.Q
	if q == nil {
		return zkp.ModularGroup{}, ErrPrimeOrderRequired
	}
	return zkp.ModularGroup{P: c.p, Q: q}, nil
}

// GenerateThresholdKeys implements phe.ThresholdDecrypter. Verification keys
// g^share are published to verify partial decryptions.
func (c *Cryptosystem) GenerateThresholdKeys(t, parties int) ([]byte, [][]byte, error) {
	if !c.hasSecret {
		return nil, nil, phe.ErrMissingPrivateKey
	}
	group, err := c.group()
	if err != nil {
		return nil, nil, err
	}
	if big.NewInt(int64(parties)).Cmp(group.Q) >= 0 {
		return nil, nil, fmt.Errorf("lightphe: number of parties must be less than the group order %s", group.Q)
	}
	shares, err := threshold.SplitSecret(c.x, t, parties, group.Q)
	if err != nil {
		return nil, nil, err
	}
	verificationKeys := make([]*big.Int, parties)
	for i, share := range shares {
		verificationKeys[i] = new(big.Int).Exp(c.g, share, c.p)
	}

	pk := *c.keys.PublicKey
	pk.Threshold, pk.Parties, pk.VerificationKeys = t, parties, verificationKeys
	publicKey, err := json.Marshal(Keys{PublicKey: &pk})
	if err != nil {
		return nil, nil, err
	}
	shareKeys, err := threshold.ShareKeys(shares, func(key *phe.ThresholdKey) interface{} {
		return Keys{PublicKey: &pk, ThresholdKey: key}
	})
	return publicKey, shareKeys, err
}

// PartialDecrypt implements phe.ThresholdDecrypter. The partial decryption is
// c1^share.
func (c *Cryptosystem) PartialDecrypt(ciphertext phe.Value, prove bool) (*phe.PartialDecryption, error) {
	key := c.keys.ThresholdKey
	if key == nil {
		return nil, threshold.ErrNoThresholdKey
	}
	c1, _, err := c.components(ciphertext)
	if err != nil {
		return nil, err
	}
	value := new(big.Int).Exp(c1, key.Share, c.p)
	partial := &phe.PartialDecryption{Index: key.Index, Value: phe.Int{V: value}}
	if !prove {
		return partial, nil
	}
	group, err := c.group()
	if err != nil {
		return nil, err
	}
	proof, err := zkp.ProveDLEQ(group, c.g, new(big.Int).Exp(c.g, key.Share, c.p), c1, value, key.Share,
		PartialDecryptionDomain, []interface{}{c.p, key.Index})
	if err != nil {
		return nil, err
	}
	partial.Proof = proof
	return partial, nil
}

// VerifyPartialDecryption implements phe.ThresholdDecrypter.
func (c *Cryptosystem) VerifyPartialDecryption(ciphertext phe.Value, partial *phe.PartialDecryption) (bool, error) {
	verificationKeys := c.keys.PublicKey.VerificationKeys
	if verificationKeys == nil {
		return false, threshold.ErrNoVerificationKeys
	}
	group, err := c.group()
	if err != nil {
		return false, err
	}
	if partial == nil || partial.Index < 1 || partial.Index > len(verificationKeys) {
		return false, nil
	}
	c1, _, err := c.components(ciphertext)
	if err != nil {
		return false, nil
	}
	value, err := phe.AsInt(partial.Value)
	if err != nil {
		return false, nil
	}
	return zkp.VerifyDLEQ(group, c.g, verificationKeys[partial.Index-1], c1, value, partial.Proof,
		PartialDecryptionDomain, []interface{}{c.p, partial.Index}), nil
}

// CombinePartialDecryptions implements phe.ThresholdDecrypter. c1^x is
// restored in the exponent with lagrange interpolation.
func (c *Cryptosystem) CombinePartialDecryptions(ciphertext phe.Value, partials []*phe.PartialDecryption, verify bool) (
	*big.Int, error) {
	group, err := c.group()
	if err != nil {
		return nil, err
	}
	_, c2, err := c.components(ciphertext)
	if err != nil {
		return nil, err
	}
	var verifier func(*phe.PartialDecryption) (bool, error)
	if verify {
		verifier = func(partial *phe.PartialDecryption) (bool, error) {
			return c.VerifyPartialDecryption(ciphertext, partial)
		}
	}
	pk := c.keys.PublicKey
	selected, err := threshold.Select(pk.Threshold, pk.Parties, partials, verifier)
	if err != nil {
		return nil, err
	}
	indices := threshold.Indices(selected)

	c1x := big.NewInt(1)
	for _, partial := range selected {
		value, err := phe.AsInt(partial.Value)
		if err != nil {
			return nil, err
		}
		coefficient, err := threshold.LagrangeCoefficient(partial.Index, indices, group.Q)
		if err != nil {
			return nil, err
		}
		c1x.Mul(c1x, new(big.Int).Exp(value, coefficient, c.p)).Mod(c1x, c.p)
	}

	inverse, err := mathutil.ModInverse(c1x, c.p)
	if err != nil {
		return nil, fmt.Errorf("elgamal: %v: %w", err, phe.ErrDecryptionFailed)
	}
	return c.restorePlaintext(inverse.Mul(inverse, c2).Mod(inverse, c.p))
}

// DecryptWithProof implements phe.DecryptionProver. Chaum-Pedersen proof
// shows that log_g(y) = log_c1(c1^x) without revealing the private key.
func (c *Cryptosystem) DecryptWithProof(ciphertext phe.Value) (*big.Int, *phe.ZKProof, error) {
	if !c.hasSecret {
		return nil, nil, phe.ErrMissingPrivateKey
	}
	group, err := c.group()
	if err != nil {
		return nil, nil, err
	}
	c1, c2, err := c.components(ciphertext)
	if err != nil {
		return nil, nil, err
	}
	c1x := new(big.Int).Exp(c1, c.x, c.p)
	proof, err := zkp.ProveDLEQ(group, c.g, c.y, c1, c1x, c.x, DecryptionDomain, []interface{}{c.p, c2})
	if err != nil {
		return nil, nil, err
	}
	inverse, err := mathutil.ModInverse(c1x, c.p)
	if err != nil {
		return nil, nil, fmt.Errorf("elgamal: %v: %w", err, phe.ErrDecryptionFailed)
	}
	plaintext, err := c.restorePlaintext(inverse.Mul(inverse, c2).Mod(inverse, c.p))
	if err != nil {
		return nil, nil, err
	}
	return plaintext, proof, nil
}

// VerifyDecryption implements phe.DecryptionProver. Exponential ElGamal
// checks the plaintext in modulo q.
func (c *Cryptosystem) VerifyDecryption(ciphertext phe.Value, plaintext *big.Int, proof *phe.ZKProof) (bool, error) {
	group, err := c.group()
	if err != nil {
		return false, err
	}
	c1, c2, err := c.components(ciphertext)
	if err != nil || plaintext == nil || !group.IsMember(c1) || c2.Sign() <= 0 || c2.Cmp(c.p) >= 0 {
		return false, nil
	}

	// c1^x implied by the claimed plaintext
	var c1x *big.Int
	if c.exponential {
		c1x = new(big.Int).Exp(c.g, new(big.Int).Mod(new(big.Int).Neg(plaintext), group.Q), c.p)
	} else {
		if new(big.Int).Mod(plaintext, c.p).Sign() == 0 {
			return false, nil
		}
		if c1x, err = mathutil.ModInverse(plaintext, c.p); err != nil {
			return false, nil
		}
	}
	c1x.Mul(c1x, c2).Mod(c1x, c.p)
	return zkp.VerifyDLEQ(group, c.g, c.y, c1, c1x, proof, DecryptionDomain, []interface{}{c.p, c2}), nil
}

// GenerateRandomKey implements phe.MembershipProver.
func (c *Cryptosystem) GenerateRandomKey() (*big.Int, error) {
	return mathutil.RandRange(big.NewInt(1), new(big.Int).Sub(c.p, big.NewInt(1)))
}

// requireExponential reports proofs of allowed values for regular ElGamal.
func (c *Cryptosystem) requireExponential() error {
	if !c.exponential {
		return fmt.Errorf("lightphe: ElGamal does not support proving that a ciphertext encrypts one of given values, "+
			"use Exponential-ElGamal instead: %w", phe.ErrUnsupportedOperation)
	}
	return nil
}

// EncryptWithProof implements phe.MembershipProver. Disjunctive
// Chaum-Pedersen proof shows that c2 / g^v is y^r for one of the values v.
// Only exponential ElGamal supports this.
func (c *Cryptosystem) EncryptWithProof(plaintext *big.Int, values []*big.Int, context interface{}) (
	phe.Value, *phe.ZKProof, error) {
	if err := c.requireExponential(); err != nil {
		return nil, nil, err
	}
	r, err := c.GenerateRandomKey()
	if err != nil {
		return nil, nil, err
	}
	ciphertext, err := c.EncryptWith(plaintext, r)
	if err != nil {
		return nil, nil, err
	}
	proof, err := c.ProveMembership(ciphertext, plaintext, r, values, context)
	if err != nil {
		return nil, nil, err
	}
	return ciphertext, proof, nil
}

// ProveMembership implements phe.MembershipProver.
func (c *Cryptosystem) ProveMembership(ciphertext phe.Value, plaintext, randomKey *big.Int, values []*big.Int,
	context interface{}) (*phe.ZKProof, error) {
	if err := c.requireExponential(); err != nil {
		return nil, err
	}
	group, err := c.group()
	if err != nil {
		return nil, err
	}
	c1, c2, err := c.components(ciphertext)
	if err != nil {
		return nil, err
	}
	index, err := zkp.IndexOf(plaintext, values)
	if err != nil {
		return nil, err
	}
	return zkp.ProveDLEQOr(group, c.g, c1, c.y, c.membershipCandidates(c2, values, group.Q), randomKey, index,
		MembershipDomain, []interface{}{c.p, c2, values, context})
}

// CombineRandomKeys implements phe.MembershipProver. c1 = g^r multiplies, so
// random keys add.
func (c *Cryptosystem) CombineRandomKeys(randomKeys []*big.Int) *big.Int {
	sum := new(big.Int)
	for _, r := range randomKeys {
		sum.Add(sum, r)
	}
	return sum
}

// VerifyCiphertext implements phe.MembershipProver.
func (c *Cryptosystem) VerifyCiphertext(ciphertext phe.Value, proof *phe.ZKProof, values []*big.Int,
	context interface{}) (bool, error) {
	if err := c.requireExponential(); err != nil {
		return false, err
	}
	group, err := c.group()
	if err != nil {
		return false, err
	}
	c1, c2, err := c.components(ciphertext)
	if err != nil {
		return false, nil
	}
	return zkp.VerifyDLEQOr(group, c.g, c1, c.y, c.membershipCandidates(c2, values, group.Q), proof,
		MembershipDomain, []interface{}{c.p, c2, values, context}), nil
}

// membershipCandidates returns c2 / g^v for each value v. A ciphertext
// encrypts v if and only if its candidate is y^r where c1 = g^r.
func (c *Cryptosystem) membershipCandidates(c2 *big.Int, values []*big.Int, q *big.Int) []zkp.Element {
	out := make([]zkp.Element, len(values))
	for i, v := range values {
		candidate := new(big.Int).Exp(c.g, new(big.Int).Mod(new(big.Int).Neg(v), q), c.p)
		out[i] = candidate.Mul(candidate, c2).Mod(candidate, c.p)
	}
	return out
}

// knowledgeDomain separates proofs of knowledge of ElGamal and exponential
// ElGamal.
func (c *Cryptosystem) knowledgeDomain() string {
	if c.exponential {
		return "lightphe/exponential-elgamal/knowledge"
	}
	return "lightphe/elgamal/knowledge"
}

// EncryptWithProofOfKnowledge implements phe.KnowledgeProver. Schnorr proof
// shows knowledge of r where c1 = g^r, which reveals the plaintext from c2.
// It is bound to c2, so a copied, re-randomized or modified ciphertext of
// someone else cannot be proven.
func (c *Cryptosystem) EncryptWithProofOfKnowledge(plaintext *big.Int, context interface{}) (phe.Value, *phe.ZKProof, error) {
	group, err := c.group()
	if err != nil {
		return nil, nil, err
	}
	r, err := c.GenerateRandomKey()
	if err != nil {
		return nil, nil, err
	}
	ciphertext, err := c.EncryptWith(plaintext, r)
	if err != nil {
		return nil, nil, err
	}
	c1, c2, _ := c.components(ciphertext)
	proof, err := zkp.ProveDLog(group, c.g, c1, r, c.knowledgeDomain(), []interface{}{c.p, c2, context})
	if err != nil {
		return nil, nil, err
	}
	return ciphertext, proof, nil
}

// VerifyKnowledge implements phe.KnowledgeProver.
func (c *Cryptosystem) VerifyKnowledge(ciphertext phe.Value, proof *phe.ZKProof, context interface{}) (bool, error) {
	group, err := c.group()
	if err != nil {
		return false, err
	}
	c1, c2, err := c.components(ciphertext)
	if err != nil || c2.Sign() <= 0 || c2.Cmp(c.p) >= 0 {
		return false, nil
	}
	return zkp.VerifyDLog(group, c.g, c1, proof, c.knowledgeDomain(), []interface{}{c.p, c2, context}), nil
}
