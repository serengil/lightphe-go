package zkp

import (
	"math/big"

	"github.com/serengil/lightphe-go/lightphe/ecc"
	"github.com/serengil/lightphe-go/lightphe/internal/mathutil"
	"github.com/serengil/lightphe-go/lightphe/phe"
)

// Element is an element of a Group: a *big.Int of a ModularGroup, or an
// ecc.Point of an EllipticCurveGroup.
type Element = interface{}

// Group is a cyclic group of a known prime order, which Chaum-Pedersen and
// Schnorr proofs work in.
type Group interface {
	// Order is the prime order q of the group.
	Order() *big.Int

	// Exp returns base^k.
	Exp(base Element, k *big.Int) (Element, error)

	// Mul returns a * b.
	Mul(a, b Element) (Element, error)

	// IsMember reports whether a is in the group of prime order. Soundness of
	// proofs requires it.
	IsMember(a Element) bool

	// Encode returns the form of an element hashed into challenges.
	Encode(a Element) interface{}
}

// ModularGroup is the subgroup of prime order Q in the multiplicative group of
// integers modulo the prime P.
type ModularGroup struct {
	P, Q *big.Int
}

var _ Group = ModularGroup{}

// Order implements Group.
func (g ModularGroup) Order() *big.Int { return g.Q }

// Exp implements Group.
func (g ModularGroup) Exp(base Element, k *big.Int) (Element, error) {
	b, ok := base.(*big.Int)
	if !ok {
		return nil, phe.InvalidCiphertextf("zkp: expected an integer group element, got %T", base)
	}
	return new(big.Int).Exp(b, new(big.Int).Mod(k, g.Q), g.P), nil
}

// Mul implements Group.
func (g ModularGroup) Mul(a, b Element) (Element, error) {
	x, ok1 := a.(*big.Int)
	y, ok2 := b.(*big.Int)
	if !ok1 || !ok2 {
		return nil, phe.InvalidCiphertextf("zkp: expected integer group elements")
	}
	product := new(big.Int).Mul(x, y)
	return product.Mod(product, g.P), nil
}

// IsMember implements Group.
func (g ModularGroup) IsMember(a Element) bool {
	x, ok := a.(*big.Int)
	if !ok || x == nil || x.Sign() <= 0 || x.Cmp(g.P) >= 0 {
		return false
	}
	return new(big.Int).Exp(x, g.Q, g.P).Cmp(big.NewInt(1)) == 0
}

// Encode implements Group.
func (g ModularGroup) Encode(a Element) interface{} { return a }

// EllipticCurveGroup is the subgroup generated by the base point of an
// elliptic curve. Its operation is written multiplicatively here, i.e. Exp is
// scalar multiplication and Mul is addition of points.
type EllipticCurveGroup struct {
	EC *ecc.ECC
}

var _ Group = EllipticCurveGroup{}

// Order implements Group.
func (g EllipticCurveGroup) Order() *big.Int { return g.EC.N() }

// Exp implements Group.
func (g EllipticCurveGroup) Exp(base Element, k *big.Int) (Element, error) {
	p, ok := base.(ecc.Point)
	if !ok || p.Curve() == nil {
		return nil, phe.InvalidCiphertextf("zkp: expected a curve point, got %T", base)
	}
	return p.ScalarMul(new(big.Int).Mod(k, g.EC.N()))
}

// Mul implements Group.
func (g EllipticCurveGroup) Mul(a, b Element) (Element, error) {
	p, ok1 := a.(ecc.Point)
	q, ok2 := b.(ecc.Point)
	if !ok1 || !ok2 || p.Curve() == nil || q.Curve() == nil {
		return nil, phe.InvalidCiphertextf("zkp: expected curve points")
	}
	return p.Add(q)
}

// IsMember implements Group. A point is in the subgroup if n * p is the
// neutral element, computed as (n - 1) * p + p because scalar multiplication
// reduces the scalar modulo n.
func (g EllipticCurveGroup) IsMember(a Element) bool {
	p, ok := a.(ecc.Point)
	if !ok || p.Curve() == nil {
		return false
	}
	if p.IsIdentity() {
		return true
	}
	partial, err := p.ScalarMul(new(big.Int).Sub(g.EC.N(), big.NewInt(1)))
	if err != nil {
		return false
	}
	total, err := partial.Add(p)
	return err == nil && total.IsIdentity()
}

// Encode implements Group.
func (g EllipticCurveGroup) Encode(a Element) interface{} { return a }

// randomExponent returns a uniform random value in [1, q - 1].
func randomExponent(q *big.Int) (*big.Int, error) {
	return mathutil.RandRange(big.NewInt(1), new(big.Int).Sub(q, big.NewInt(1)))
}

// commitment returns g^z * h^(-e), the commitment of an honest prover.
func commitment(group Group, g, h Element, z, e *big.Int) (Element, error) {
	gz, err := group.Exp(g, z)
	if err != nil {
		return nil, err
	}
	he, err := group.Exp(h, new(big.Int).Neg(e))
	if err != nil {
		return nil, err
	}
	return group.Mul(gz, he)
}

func encodeAll(group Group, elements ...Element) []interface{} {
	out := make([]interface{}, len(elements))
	for i, element := range elements {
		out[i] = group.Encode(element)
	}
	return out
}

// inRange reports whether 0 <= x < bound.
func inRange(x, bound *big.Int) bool {
	return x != nil && x.Sign() >= 0 && x.Cmp(bound) < 0
}
